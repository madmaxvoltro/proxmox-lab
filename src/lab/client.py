"""Thin client for the user's PC (Windows first, portable paths). It holds no logic of its own:
almost every command is forwarded to `lab` on the Proxmox host over SSH (Tailscale SSH), so the
host's identity, quota and approval rules always apply. Local extras: setup, ssh, ssh-config,
mcp-config, put/get of local files, and a local confirmation for delete."""

import json
import os
import shlex
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

CONFIG_PATH = Path.home() / ".lab" / "client.toml"
SSH_CONFIG = Path.home() / ".ssh" / "config"
BEGIN = "# >>> lab managed block (generated by `lab ssh-config`; edits here are overwritten) >>>"
END = "# <<< lab managed block <<<"
LOCAL = ("setup", "ssh", "ssh-config", "mcp-config", "put", "get", "delete")
MAX_PUT = 4 << 20


class ClientError(Exception):
    pass


# config -----------------------------------------------------------------------------------
def load_config(path: Path = CONFIG_PATH) -> dict:
    if not path.exists():
        raise ClientError("not set up; run `lab setup HOST` (HOST = the Proxmox host's tailnet name)")
    with open(path, "rb") as fh:
        data = tomllib.load(fh)
    if not data.get("host"):
        raise ClientError(f"{path} has no host")
    return {"host": data["host"], "ssh_user": data.get("ssh_user", "root")}


def save_config(host: str, ssh_user: str, path: Path = CONFIG_PATH) -> None:
    if any(c in host + ssh_user for c in " \t\n\"'\\"):
        raise ClientError("host and user must not contain spaces or quotes")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f'host = "{host}"\nssh_user = "{ssh_user}"\n', encoding="utf-8", newline="\n")


# ssh plumbing ------------------------------------------------------------------------------
def target(cfg: dict) -> str:
    return f"{cfg['ssh_user']}@{cfg['host']}"


def remote_argv(cfg: dict, args: list, *, tty: bool = False, extra: list | None = None) -> list:
    """ssh command line that runs `lab ARGS` on the host (args are quoted for the remote POSIX shell)."""
    return ["ssh", "-t" if tty else "-T", *(extra or []), target(cfg), shlex.join(["lab", *args])]


def wants_tty(argv: list, stdin_tty: bool, stdout_tty: bool) -> bool:
    """Give the host a terminal (so it draws its live progress window) when you are at one yourself.
    Never for machine-readable or binary traffic: --json, put/get (file bytes), exec, mcp."""
    cmd = next((a for a in argv if not a.startswith("-")), "")
    return bool(stdin_tty and stdout_tty and cmd and "--json" not in argv and cmd not in ("put", "get", "mcp", "exec"))


def run_remote(cfg, args, *, stdin=None, stdout=None, capture=False, tty=False):
    # with a terminal ssh would print "Connection to host closed."; LogLevel=ERROR keeps real errors only
    cmd = remote_argv(cfg, args, tty=tty, extra=["-o", "LogLevel=ERROR"] if tty else None)
    if capture:
        return subprocess.run(cmd, capture_output=True, text=True, stdin=stdin)
    return subprocess.run(cmd, stdin=stdin, stdout=stdout)


def remote_json(cfg, args):
    # --json is a global option: it has to come before the subcommand
    res = run_remote(cfg, args if "--json" in args else ["--json", *args], capture=True)
    if res.returncode != 0:
        raise ClientError((res.stderr or res.stdout or "remote command failed").strip())
    return json.loads(res.stdout)


# ssh-config managed block -------------------------------------------------------------------------
def render_block(cfg: dict, projects: list) -> str:
    lines = [BEGIN, "Host lab-host", f"  HostName {cfg['host']}", f"  User {cfg['ssh_user']}"]
    for p in projects:
        if p.get("tailnet_name") and p.get("owner"):
            lines += [f"Host lab-{p['name']}", f"  HostName {p['tailnet_name']}", f"  User {p['owner']}"]
    lines.append(END)
    return "\n".join(lines) + "\n"


def merge_block(existing: str, block: str) -> str:
    """Replace the managed block, or append it. Everything outside the markers is left untouched."""
    if BEGIN in existing and END in existing:
        head, _, rest = existing.partition(BEGIN)
        _, _, tail = rest.partition(END)
        return head + block.rstrip("\n") + tail
    sep = "" if not existing or existing.endswith("\n\n") else ("\n" if existing.endswith("\n") else "\n\n")
    return existing + sep + block


def write_ssh_config(block: str, path: Path = SSH_CONFIG) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8") if path.exists() else ""
    backup = path.with_name(path.name + ".lab-backup")
    if existing and BEGIN not in existing and not backup.exists():
        backup.write_text(existing, encoding="utf-8")
    path.write_text(merge_block(existing, block), encoding="utf-8", newline="\n")


# mcp config ---------------------------------------------------------------------------------------------
def mcp_server_entry(cfg: dict) -> dict:
    return {"command": "ssh", "args": ["-T", "-o", "BatchMode=yes", "-o", "ServerAliveInterval=30",
                                       target(cfg), "lab", "mcp"]}


# commands ------------------------------------------------------------------------------------------------
def cmd_setup(argv):
    if not argv or argv[0].startswith("-"):
        raise ClientError("usage: lab setup HOST [--user SSH_USER]")
    user = argv[argv.index("--user") + 1] if "--user" in argv[1:] else "root"
    save_config(argv[0], user)
    print(f"saved {CONFIG_PATH}\nNext: `lab ssh-config`, then `lab mcp-config`.")
    return 0


def cmd_ssh(cfg, argv):
    if not argv:
        raise ClientError("usage: lab ssh NAME [--via-host]")
    name, via_host = argv[0], "--via-host" in argv[1:]
    p = remote_json(cfg, ["status", name])
    if p.get("state") != "running":
        raise ClientError(f"{name} is {p.get('state')}; run `lab start {name}`")
    owner = p.get("owner")
    if not owner or not p.get("tailnet_name"):
        raise ClientError(f"{name} has no tailnet name")
    cmd = ["ssh"]
    if via_host:
        cmd += ["-J", target(cfg), f"{owner}@{p['tailnet_ip']}"]
    else:
        cmd += [f"{owner}@{p['tailnet_name']}"]
    return subprocess.run(cmd).returncode


def cmd_ssh_config(cfg):
    projects = remote_json(cfg, ["list"])
    write_ssh_config(render_block(cfg, projects))
    n = sum(1 for p in projects if p.get("tailnet_name"))
    print(f"updated {SSH_CONFIG}: lab-host and {n} project host(s) (e.g. `ssh lab-NAME`, VS Code Remote-SSH)")
    return 0


def cmd_mcp_config(cfg):
    entry = mcp_server_entry(cfg)
    print("Claude Desktop (claude_desktop_config.json) / any MCP client:")
    print(json.dumps({"mcpServers": {"lab": entry}}, indent=2))
    print("\nClaude Code:")
    print("  claude mcp add lab -- " + " ".join(shlex.quote(x) if os.name != "nt" else x for x in [entry["command"], *entry["args"]]))
    return 0


def cmd_put(cfg, argv):
    if len(argv) != 3:
        raise ClientError("usage: lab put NAME LOCAL_SRC REMOTE_DST")
    name, src, dst = argv
    p = Path(src)
    if not p.is_file():
        raise ClientError(f"no such file: {src}")
    if p.stat().st_size > MAX_PUT:
        raise ClientError(f"{src} is over {MAX_PUT} bytes; use scp (`ssh-config` gives you lab-NAME)")
    with open(p, "rb") as fh:
        return run_remote(cfg, ["put", name, dst], stdin=fh).returncode


def cmd_get(cfg, argv):
    if len(argv) != 3:
        raise ClientError("usage: lab get NAME REMOTE_SRC LOCAL_DST")
    name, src, dst = argv
    tmp = Path(dst + ".part")
    with open(tmp, "wb") as fh:
        rc = run_remote(cfg, ["get", name, src], stdout=fh).returncode
    if rc != 0:
        tmp.unlink(missing_ok=True)
        return rc
    os.replace(tmp, dst)
    return 0


def cmd_delete(cfg, argv):
    pos = [a for a in argv if not a.startswith("-")]
    if "--yes" not in argv:
        if len(pos) != 1:
            raise ClientError("usage: lab delete NAME [--archives] [--force]")
        if input(f"Type the project name ({pos[0]}) to confirm deletion: ").strip() != pos[0]:
            print("not confirmed")
            return 1
        argv = [*argv, "--yes"]
    return run_remote(cfg, ["delete", *argv]).returncode


def cmd_check() -> int:
    """Is this PC ready? Verifies what lab.exe ships with and what it needs from Windows. Exit code 0
    unless something bundled is missing (a missing ssh or Tailscale is a warning, not a failure)."""
    from . import __version__, distros, watch
    rows = [
        ("lab", f"{__version__}" + (" (packaged exe)" if getattr(sys, "frozen", False) else ""), True, True),
        ("popup script", "bundled" if watch.SCRIPT.is_file() else "MISSING", watch.SCRIPT.is_file(), True),
        ("distro catalogue", f"{len(distros.load(override=None))} distros", True, True),
        ("OpenSSH client", shutil.which("ssh") or "not found: install it from Settings > Optional features", bool(shutil.which("ssh")), False),
        ("Tailscale", shutil.which("tailscale") or "not found: https://tailscale.com/download", bool(shutil.which("tailscale")), False),
    ]
    try:
        host = load_config()["host"]
        rows.append(("host", f"{host} (settings found)", True, False))
    except ClientError:
        rows.append(("host", "not set up yet: run `lab connect`", False, False))
    bad = 0
    for name, text, ok, required in rows:
        print(f"  {'ok  ' if ok else ('FAIL' if required else 'warn')} {name:<18} {text}")
        bad += (not ok) and required
    return 1 if bad else 0


def remove_from_path(value: str, folder: str) -> str:
    """`value` (a ;-separated PATH) without `folder`, compared the way Windows does (case-insensitive)."""
    keep = [p for p in value.split(";") if p and p.rstrip("\\").lower() != folder.rstrip("\\").lower()]
    return ";".join(keep)


def cmd_uninstall() -> int:
    """Remove the installed lab.exe, its PATH entry and its login launcher. Settings are left alone."""
    if not getattr(sys, "frozen", False):
        print("This copy was installed with pip: run `python -m pip uninstall project-lab`.")
        return 0
    import winreg
    from . import watch
    exe = Path(sys.executable)
    if input(f"Remove {exe.parent} and the approval helper's login launcher? [y/N] ").strip().lower() not in ("y", "yes"):
        return 1
    watch.uninstall()
    with winreg.OpenKey(winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE) as key:
        try:
            current, kind = winreg.QueryValueEx(key, "Path")
            winreg.SetValueEx(key, "Path", 0, kind, remove_from_path(current, str(exe.parent)))
        except FileNotFoundError:
            pass
    # a running program cannot delete itself: let a detached shell do it a moment after we exit
    subprocess.Popen(f'cmd /c ping -n 3 127.0.0.1 >nul & rmdir /s /q "{exe.parent}"', shell=True,
                     creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0), close_fds=True)
    print("Removed. Left in place: ~/.lab (settings), the lab block in ~/.ssh/config, and the \"lab\" entry in\n"
          "Claude Desktop's config. Delete them by hand if you want those gone too.")
    return 0


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    try:
        if argv[:1] == ["check"]:
            return cmd_check()
        if argv[:1] == ["uninstall"]:
            return cmd_uninstall()
        if argv[:1] in (["version"], ["--version"]):
            from . import __version__
            print(f"lab {__version__} (this PC)")
            return 0
        if argv[:1] == ["setup"]:
            return cmd_setup(argv[1:])
        if argv[:1] == ["connect"]:
            from . import connect
            return connect.run(argv[1:])
        cfg = load_config()
        if argv[:1] == ["watch"]:
            from . import watch
            return watch.main(cfg, argv[1:])
        if argv[:1] == ["ssh"]:
            return cmd_ssh(cfg, argv[1:])
        if argv[:1] == ["ssh-config"]:
            return cmd_ssh_config(cfg)
        if argv[:1] == ["mcp-config"]:
            return cmd_mcp_config(cfg)
        if argv[:1] == ["put"]:
            return cmd_put(cfg, argv[1:])
        if argv[:1] == ["get"]:
            return cmd_get(cfg, argv[1:])
        if argv[:1] == ["delete"]:
            return cmd_delete(cfg, argv[1:])
        # everything else runs on the host; at a real terminal it gets one too, so progress is live
        return run_remote(cfg, argv, tty=wants_tty(argv, sys.stdin.isatty(), sys.stdout.isatty())).returncode
    except ClientError as e:
        print(f"error: {e}", file=sys.stderr)
        return 3
    except FileNotFoundError:
        print("error: ssh not found; install the OpenSSH client", file=sys.stderr)
        return 3
    except KeyboardInterrupt:
        return 130


if __name__ == "__main__":
    sys.exit(main())
